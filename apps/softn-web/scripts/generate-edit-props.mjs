/**
 * The props of each component that a plain value can be written for, for the
 * runtime's editor (src/edit/): when a person picks a `<Button>` on a running
 * app, these are the fields it offers. Taken from @softn/components'
 * component-manifest.json, which is what the Builder's property panel reads
 * too, and kept to what the editor needs of it: about a twentieth of the
 * manifest, fetched with the editor and not before.
 *
 *   node apps/softn-web/scripts/generate-edit-props.mjs
 *
 * test/editProps.test.ts holds the written file to what this makes.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MANIFEST = new URL('../../../packages/@softn/components/component-manifest.json', import.meta.url);
const OUTPUT = new URL('../src/edit/componentProps.generated.ts', import.meta.url);

/** Props every component has that are not a person's to set from here. */
const SKIPPED = new Set(['className', 'style', 'children', 'key', 'ref']);

/**
 * What a prop takes, as the editor reads it: 's' words, 'n' a number, 'b' yes
 * or no, a list of the words it takes (ending in '*' where any others are
 * taken too), or undefined for one that is no plain value.
 */
function plainKind(type) {
  switch (type?.kind) {
    case 'string':
      return 's';
    case 'number':
      return 'n';
    case 'boolean':
      return 'b';
    case 'enum':
      return Array.isArray(type.options) && type.options.length > 0 ? [...type.options] : undefined;
    case 'other':
      return Array.isArray(type.literals) && type.literals.length > 0 && /\|\s*string\b/.test(type.text ?? '') ? [...type.literals, '*'] : undefined;
    default:
      return undefined;
  }
}

/** Each registered component's plain props, by name, in the manifest's order. */
export function plainProps(manifest) {
  const registered = new Set(Object.values(manifest.registered ?? {}).flat());
  const components = {};
  for (const component of manifest.components ?? []) {
    if (!registered.has(component.name)) continue;
    const props = {};
    for (const member of component.props?.members ?? []) {
      if (SKIPPED.has(member.name) || /^on[A-Z]/.test(member.name)) continue;
      const kind = plainKind(member.type);
      if (kind !== undefined) props[member.name] = kind;
    }
    components[component.name] = props;
  }
  return components;
}

export function render(components) {
  const lines = Object.entries(components).map(([name, props]) => `  ${JSON.stringify(name)}: ${JSON.stringify(props)},`);
  return [
    "// Generated by scripts/generate-edit-props.mjs from @softn/components' component-manifest.json; do not edit.",
    '// Regenerate with `node apps/softn-web/scripts/generate-edit-props.mjs`. Read by src/edit/pickFields.ts.',
    '',
    "/** A prop a plain value can be written for: 's' words, 'n' a number, 'b' yes or no, or the words it takes ('*' last: any others too). */",
    "export type PlainProp = 's' | 'n' | 'b' | readonly string[];",
    '',
    "/** Each registered component's props that take a plain value, by name. */",
    'export const COMPONENT_PROPS: Readonly<Record<string, Readonly<Record<string, PlainProp>>>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const components = plainProps(JSON.parse(readFileSync(MANIFEST, 'utf8')));
  writeFileSync(OUTPUT, render(components));
  console.log(`[edit-props] ${Object.keys(components).length} components written to src/edit/componentProps.generated.ts`);
}
