/**
 * Write `src/utils/componentProps.generated.ts`: for each component the
 * library registers, each prop its interface declares, with what
 * `packages/@softn/components/component-manifest.json` knows of it — the
 * default the component gives it when a page writes nothing, whether that
 * default is one the manifest cannot read, and the choices its type names.
 *
 * The property panel shows an unwritten prop as that default and writes
 * nothing when it is chosen, so it has to be the component's own. The
 * registry (src/utils/componentRegistry.ts) used to say it by hand, and said
 * it wrong for a hundred props. The manifest is 330 KB and is not shipped;
 * this is the part of it the Builder reads.
 *
 * `src/utils/componentRegistry.manifest.test.ts` and `check:components` fail
 * when the module is stale. Regenerate after the manifest with
 *
 *     npm run generate:component-props -w @softn/builder
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const builderRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const manifestPath = resolve(builderRoot, '../../packages/@softn/components/component-manifest.json');
export const componentPropsPath = join(builderRoot, 'src', 'utils', 'componentProps.generated.ts');

/** The module's text for `manifest`. */
export function renderComponentProps(manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))) {
  const registered = new Set(Object.values(manifest.registered).flat());
  const lines = [];
  for (const component of [...manifest.components].sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    if (!registered.has(component.name)) continue;
    const props = {};
    for (const member of component.props?.members ?? []) {
      const facts = {};
      if ('default' in member) facts.default = member.default;
      else if (member.defaultUnknown) facts.defaultUnknown = true;
      // An enum's options are all it takes; an open union's literals are the
      // ones it names among the other values it takes.
      if (member.type.kind === 'enum' && member.type.options) facts.options = member.type.options;
      else if (member.type.literals) {
        facts.options = member.type.literals;
        facts.takesOthers = true;
      }
      props[member.name] = facts;
    }
    lines.push(`  ${JSON.stringify(component.name)}: ${JSON.stringify(props)},`);
  }
  return [
    '// Generated by scripts/generate-component-props.mjs from component-manifest.json; do not edit.',
    '// Regenerate with `npm run generate:component-props -w @softn/builder`. Read by componentRegistry.ts.',
    '',
    '/** What the component manifest knows of one prop. */',
    'export interface ManifestPropFacts {',
    '  /** What the component does with the prop when a page writes nothing. */',
    '  default?: unknown;',
    '  /** The component works out a default the manifest cannot read. Neither field: it has none. */',
    '  defaultUnknown?: true;',
    '  /** The string literals its type names. */',
    '  options?: string[];',
    "  /** Its type takes values beyond `options` (`'sm' | 'md' | string`). */",
    '  takesOthers?: true;',
    '}',
    '',
    '/** Each registered component\'s declared props, by name. */',
    'export const COMPONENT_PROPS: Readonly<Record<string, Readonly<Record<string, ManifestPropFacts>>>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeFileSync(componentPropsPath, renderComponentProps());
  console.log(`wrote ${relative(process.cwd(), componentPropsPath)}`);
}
