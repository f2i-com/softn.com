import { sha256Hex } from './crypto';

/** Editor-built modules run at the original source URL, so relative imports keep their base. */
const GENERATED_ROOT = '__softn_generated__/';
export const GENERATED_SOURCE_HEADER = '// Generated by SoftN from component source.\n';
const DIGEST_PREFIX = GENERATED_SOURCE_HEADER + '// SoftN source SHA-256: ';

/** Compiled Vue modules can embed their own source path. A BOM is a decoding marker. */
export function sourceModuleHeader(path: string, source: string): Promise<string> {
  const bytes = new TextEncoder().encode(path + '\0' + source.replace(/^\uFEFF/, ''));
  return sha256Hex(bytes).then(hash => DIGEST_PREFIX + hash + '\n');
}

export async function checkSourceModules(files: ReadonlyMap<string, string>): Promise<void> {
  for (const [path, source] of files) {
    const output = compiledSourcePath(path);
    if (!output) continue;
    const code = files.get(output);
    // Modules from earlier exports carry only the first comment and still run as before.
    if (code?.startsWith(DIGEST_PREFIX) && !code.startsWith(await sourceModuleHeader(path, source))) {
      throw new Error(`${path} has changed since its JavaScript was generated. Open the project in SoftN Studio or Builder and export it again.`);
    }
  }
}

export function generatedFrameworkPath(framework: 'react' | 'vue'): string {
  return GENERATED_ROOT + 'vendor/' + framework + '.js';
}

export function compiledSourcePath(path: string): string | null {
  return /\.(?:jsx|vue)$/i.test(path) && !/^(?:server|backend|private)\//i.test(path) && !path.startsWith(GENERATED_ROOT)
    ? GENERATED_ROOT + path + '.js'
    : null;
}

export function isGeneratedSourceModule(path: string, content: string): boolean {
  if (!path.startsWith(GENERATED_ROOT) || !content.startsWith(GENERATED_SOURCE_HEADER)) return false;
  return /\.(?:jsx|vue)\.js$/i.test(path) || path === generatedFrameworkPath('react') || path === generatedFrameworkPath('vue');
}
